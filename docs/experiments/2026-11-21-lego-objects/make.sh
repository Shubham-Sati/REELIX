#!/bin/bash
# Re-makes every picture of this experiment from the code in project/custom (no pipeline run, no AI model).
# One still per object (3/4 view), the same object on green for its black silhouette, a street scene, and two contact sheets.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../../.." && pwd)"; OUT="$HERE/2-own-code"; mkdir -p "$OUT/sil"
ANIMALS="kit-tree kit-hill kit-house rocks mountain pine palm nest cottage townhouse hut car bus train bicycle motorbike boat plane"
# timeline: scene i = one animal (1 s each), then the same animals bare (green), then the zoo
python3 - "$HERE" "$ANIMALS" <<'PY'
import json, sys
here, animals = sys.argv[1], sys.argv[2].split()
sc = []
for bare in (False, True):
    for a in animals:
        sc.append({"image": "", "start": len(sc), "duration": 1, "motion": "zoom-in", "engine": "custom", "component": "O_show", "props": {"obj": a, "bare": bare}})
sc.append({"image": "", "start": len(sc), "duration": 1, "motion": "zoom-in", "engine": "custom", "component": "G_all"})
t = {"width": 1920, "height": 1080, "fps": 30, "title": "Lego objects", "accent": "#FFB703", "scenes": sc, "voice": "", "music": None, "captions": [], "durationSec": len(sc)}
json.dump(t, open(f"{here}/project/timeline.json", "w"), indent=1)
PY
SRC="$ROOT/templates/remotion/src/custom"; find "$SRC" -mindepth 1 ! -name index.ts -delete
{ echo "// Generated by make.sh. Do not edit by hand."; names=()
  for f in "$HERE"/project/custom/*.tsx; do n="$(basename "$f" .tsx)"; cp "$f" "$SRC/$n.tsx"; case "$n" in _*) continue;; esac; names+=("$n"); echo "import $n from \"./$n\";"; done
  echo "export const custom: Record<string, React.FC<any>> = { $(IFS=,; echo "${names[*]}" | sed 's/,/, /g') };"; } > "$SRC/index.ts"
cd "$ROOT/templates/remotion"
i=0; N=$(echo $ANIMALS | wc -w | tr -d ' ')
for a in $ANIMALS; do
  npx remotion still src/index.ts Main "$OUT/$a.png" --props="$HERE/project/timeline.json" --public-dir="$HERE/assets" --frame=$((i*30+20)) --gl=angle --log=error
  npx remotion still src/index.ts Main "$OUT/sil/$a-green.png" --props="$HERE/project/timeline.json" --public-dir="$HERE/assets" --frame=$(((i+N)*30+20)) --gl=angle --log=error
  # silhouette: everything that is not the green background becomes black, background white
  ffmpeg -v error -y -i "$OUT/sil/$a-green.png" -vf "colorkey=0x00ff00:0.32:0.08,format=rgba,geq=r='if(gt(alpha(X,Y),128),0,255)':g='if(gt(alpha(X,Y),128),0,255)':b='if(gt(alpha(X,Y),128),0,255)':a=255" "$OUT/sil/$a.png"
  rm "$OUT/sil/$a-green.png"; i=$((i+1))
done
npx remotion still src/index.ts Main "$OUT/all.png" --props="$HERE/project/timeline.json" --public-dir="$HERE/assets" --frame=$((2*N*30+20)) --gl=angle --log=error
# contact sheets: 5 x 3, each cell labelled
cd "$OUT"; args=(); for a in $ANIMALS; do args+=(-i "$a.png"); done
f=""; for k in $(seq 0 $((N-1))); do f="$f[$k]scale=480:-1,drawtext=text='$(echo $ANIMALS | cut -d' ' -f$((k+1)))':x=12:y=10:fontsize=28:fontcolor=black:box=1:boxcolor=white@0.7:boxborderw=6[c$k];"; done
ffmpeg -v error -y "${args[@]}" -filter_complex "${f}$(for k in $(seq 0 $((N-1))); do printf "[c$k]"; done)xstack=inputs=$N:grid=6x3" sheet.png
args=(); for a in $ANIMALS; do args+=(-i "sil/$a.png"); done
f=""; for k in $(seq 0 $((N-1))); do f="$f[$k]scale=480:-1,drawbox=c=gray:t=2[c$k];"; done
ffmpeg -v error -y "${args[@]}" -filter_complex "${f}$(for k in $(seq 0 $((N-1))); do printf "[c$k]"; done)xstack=inputs=$N:grid=6x3" silhouettes.png
echo "$OUT/sheet.png"
