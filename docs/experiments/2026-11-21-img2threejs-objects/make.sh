#!/bin/bash
# Renders every object img2threejs has built (work/<name>/createObjectModel.ts) with I_show: one still each, a sheet,
# and (with "review <name>") the 4 turntable views + comparison sheet the skill's review needs.  No pipeline run.
#   bash make.sh                 all objects listed in objects.txt that have a model
#   bash make.sh review car      front/right/back/left views of one object into work/car/review/
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../../.." && pwd)"; SRC="$ROOT/templates/remotion/src/custom"
find "$SRC" -mindepth 1 ! -name index.ts -delete
cp "$HERE"/project/custom/*.tsx "$SRC/"
{ echo "// Generated by make.sh. Do not edit by hand."; echo "import * as THREE from \"three\";"
  for d in "$HERE"/work/*/; do n=$(basename "$d"); f="$d/createObjectModel.ts"; [[ "$n" == _* ]] && continue; [ -f "$f" ] || continue
    fn=$(grep -oE "export function create[A-Za-z0-9]+Model" "$f" | head -1 | awk '{print $3}'); safe=$(echo "$n" | tr '-' '_')
    cp "$f" "$SRC/_m_$safe.ts"; echo "import { $fn as m_$safe } from \"./_m_$safe\";"; done
  echo "export const MODELS: Record<string, () => THREE.Group> = {"
  for d in "$HERE"/work/*/; do n=$(basename "$d"); [[ "$n" == _* ]] && continue; [ -f "$d/createObjectModel.ts" ] || continue; echo "  \"$n\": () => m_$(echo "$n" | tr '-' '_')(),"; done
  echo "};"; } > "$SRC/_models.ts"
{ echo "// Generated by make.sh. Do not edit by hand."; echo "import I_show from \"./I_show\";"; echo "export const custom: Record<string, React.FC<any>> = { I_show };"; } > "$SRC/index.ts"
mode=${1:-all}; one=$2
python3 - "$HERE" "$mode" "$one" <<'PY'
import json, sys, os
here, mode, one = sys.argv[1:4]
rows = [l.split("|") for l in open(f"{here}/objects.txt").read().splitlines() if l.strip() and not l.startswith("#")]
rows = [r for r in rows if os.path.exists(f"{here}/work/{r[0]}/createObjectModel.ts")]
if mode == "review": rows = [r for r in rows if r[0] == one]
sc = []
for r in rows:
    sc.append({"image": "", "start": len(sc), "duration": 1, "motion": "zoom-in", "engine": "custom", "component": "I_show", "props": {"obj": r[0], "h": float(r[1]), "l": float(r[2])}})
    if mode == "review": sc.append({"image": "", "start": len(sc), "duration": 1, "motion": "zoom-in", "engine": "custom", "component": "I_show", "props": {"obj": r[0], "h": float(r[1]), "l": float(r[2]), "strip": True}})
json.dump({"width": 1920, "height": 1080, "fps": 30, "title": "img2threejs", "accent": "#FFB703", "scenes": sc, "voice": "", "music": None, "captions": [], "durationSec": max(1, len(sc))}, open(f"{here}/project/timeline.json", "w"))
open(f"{here}/project/names.txt", "w").write(" ".join(r[0] for r in rows))
PY
cd "$ROOT/templates/remotion"; NAMES=$(cat "$HERE/project/names.txt"); OUT="$HERE/2-img2threejs"; mkdir -p "$OUT"; i=0
for a in $NAMES; do s=$(date +%s); npx remotion still src/index.ts Main "$OUT/$a.png" --props="$HERE/project/timeline.json" --public-dir="$HERE/assets" --frame=$((i*30+20)) --gl=angle --log=error; echo "render $a $(( $(date +%s) - s )) s" >> "$HERE/times.txt"; i=$((i+1)); done
if [ "$mode" = review ]; then npx remotion still src/index.ts Main "$OUT/$one-strip.png" --props="$HERE/project/timeline.json" --public-dir="$HERE/assets" --frame=50 --gl=angle --log=error; fi
if [ "$mode" = all ]; then
  cd "$OUT"; args=(); f=""; k=0
  for a in $NAMES; do args+=(-i "$a.png"); f="$f[$k]scale=480:-1,drawtext=text='$a':x=12:y=10:fontsize=28:fontcolor=black:box=1:boxcolor=white@0.7:boxborderw=6[c$k];"; k=$((k+1)); done
  while [ $((k % 6)) -ne 0 ] || [ $k -lt 6 ]; do args+=(-f lavfi -i "color=c=white:s=480x270"); f="$f[$k]null[c$k];"; k=$((k+1)); done
  ffmpeg -v error -y "${args[@]}" -filter_complex "${f}$(for j in $(seq 0 $((k-1))); do printf "[c$j]"; done)xstack=inputs=$k:grid=6x$((k/6))" -frames:v 1 -update 1 sheet.png
  echo "$OUT/sheet.png"
fi
