#!/bin/bash
# Re-makes the stills: one frame per video with captions switched ON (showCaptions true), same frame as the old render.
# Part 2 (labels): scene label + shot label in the top band. An optional 4th argument adds a test shot label ("note") to scene 0.
# Usage: bash make.sh   (run from anywhere; reads finished videos, writes only into this folder)
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../../.." && pwd)"
shot() {   # <video folder name> <seconds> <out name> [test note for scene 0]
  VD="$ROOT/videos/$1"; OUT="$HERE/$3"
  python3 -c "import json,sys;t=json.load(open('$VD/project/timeline.json'));t['showCaptions']=True;n=sys.argv[1];(n and t['scenes'][0].update(note=n));json.dump(t,open('$HERE/props-$3.json','w'))" "${4:-}"
  SRC="$ROOT/templates/remotion/src/custom"; find "$SRC" -mindepth 1 ! -name index.ts -delete
  { echo "// Generated by make.sh. Do not edit by hand."; names=()
    for f in "$VD"/project/custom/*.tsx; do [ -f "$f" ] || continue; n="$(basename "$f" .tsx)"; cp "$f" "$SRC/$n.tsx"; case "$n" in _*) continue;; esac; names+=("$n"); echo "import $n from \"./$n\";"; done
    echo "export const custom: Record<string, React.FC<any>> = { $(IFS=,; echo "${names[*]}" | sed 's/,/, /g') };"; } > "$SRC/index.ts"
  FRAME=$(python3 -c "print(int($2*30))")
  (cd "$ROOT/templates/remotion" && npx remotion still src/index.ts Main "$OUT" --props="$HERE/props-$3.json" --public-dir="$VD/assets" --frame="$FRAME" --gl=angle --log=error)
  rm "$HERE/props-$3.json"
  ffmpeg -v error -y -ss "$2" -i "$VD/final.mp4" -frames:v 1 "$HERE/before-$3"   # the old render, captions in the middle
}
