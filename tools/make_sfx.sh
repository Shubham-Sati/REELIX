#!/bin/bash
# Builds REELIX's own sound-effect library with ffmpeg only (no downloads, no licence limits).
# Re-run safely; writes library/sfx/*.wav and library/sfx/index.json.
set -e; cd "$(dirname "$0")/../library/sfx"
g() { [ -f "$1.wav" ] || ffmpeg -loglevel error -y $2 -af "$3,afade=t=out:st=$4:d=$5,loudnorm=I=-16:TP=-1.5" -ar 48000 -ac 2 "$1.wav"; }
g whoosh       "-f lavfi -i anoisesrc=d=0.9:c=pink"   "bandpass=f=900:w=1400,volume='if(lt(t,0.45),t/0.45,1)':eval=frame,highpass=f=200" 0.45 0.45
g whoosh-soft  "-f lavfi -i anoisesrc=d=0.7:c=brown"  "lowpass=f=1800,volume='if(lt(t,0.35),t/0.35,1)':eval=frame" 0.35 0.35
g impact       "-f lavfi -i sine=f=55:d=0.9"          "volume=2,aecho=0.6:0.4:40:0.3,lowpass=f=300" 0.05 0.85
g hit          "-f lavfi -i anoisesrc=d=0.25:c=white" "lowpass=f=2500,volume=1.5" 0.02 0.23
g pop          "-f lavfi -i sine=f=880:d=0.12"        "vibrato=f=40:d=0.6" 0.03 0.09
g click        "-f lavfi -i sine=f=2200:d=0.04"       "volume=1" 0.01 0.03
g ding         "-f lavfi -i sine=f=1318:d=1.2"        "aecho=0.7:0.5:60:0.4" 0.05 1.15
g riser        "-f lavfi -i anoisesrc=d=2:c=pink"     "highpass=f=300,volume='t/2':eval=frame" 1.85 0.15
g swell        "-f lavfi -i sine=f=220:d=2.2"         "volume='min(1,t/1.6)':eval=frame,aecho=0.8:0.6:120:0.5" 1.9 0.3
g fire         "-f lavfi -i anoisesrc=d=3:c=brown"    "lowpass=f=1200,tremolo=f=9:d=0.6" 2.4 0.6
g wind         "-f lavfi -i anoisesrc=d=3:c=pink"     "bandpass=f=500:w=300,tremolo=f=0.6:d=0.7" 2.2 0.8
g crowd        "-f lavfi -i anoisesrc=d=3:c=pink"     "bandpass=f=700:w=900,tremolo=f=3:d=0.5,chorus=0.6:0.9:50:0.4:0.25:2" 2.2 0.8
g typewriter   "-f lavfi -i anoisesrc=d=1.2:c=white"  "highpass=f=2000,apulsator=hz=9:amount=1" 1.0 0.2
g heartbeat    "-f lavfi -i sine=f=48:d=1.6"          "apulsator=hz=1.25:amount=1,volume=2.5" 1.3 0.3
python3 - <<'PY'
import json, subprocess, glob, os
tags = {"whoosh":"transition cut fast","whoosh-soft":"transition gentle","impact":"boom reveal big moment","hit":"punch text-slam","pop":"label appear ui","click":"ui tick","ding":"fact idea success","riser":"build-up before reveal","swell":"emotional build","fire":"flame burn heat","wind":"sky air height outdoors","crowd":"people audience cheer","typewriter":"text typing date","heartbeat":"tension suspense"}
out = []
for f in sorted(glob.glob("*.wav")):
    n = f[:-4]; d = float(subprocess.run(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",f],capture_output=True,text=True).stdout)
    out.append({"id": n, "file": f"sfx/{f}", "duration": round(d,2), "tags": tags.get(n, "generated").split(), "licence": "generated by REELIX (ffmpeg), free"})
json.dump(out, open("index.json","w"), indent=1); print(len(out), "sounds")
PY
