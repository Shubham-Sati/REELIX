#!/bin/bash
# One frame of a video as a PNG (3D looks: thumbnails and checking shots).  tools/still.sh <video_dir> <seconds> <out.png>
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; VD="$(cd "$1" && pwd)"; OUT="$3"
SRC="$ROOT/templates/remotion/src/custom"
find "$SRC" -mindepth 1 ! -name index.ts -delete
{ echo "// Generated by tools/still.sh. Do not edit by hand."; names=()
  for f in "$VD"/project/custom/*.tsx; do [ -f "$f" ] || continue; n="$(basename "$f" .tsx)"; cp "$f" "$SRC/$n.tsx"; case "$n" in _*) continue;; esac; names+=("$n"); echo "import $n from \"./$n\";"; done
  echo "export const custom: Record<string, React.FC<any>> = { $(IFS=,; echo "${names[*]}" | sed 's/,/, /g') };"; } > "$SRC/index.ts"
FPS=$(python3 -c "import json;print(json.load(open('$VD/project/timeline.json'))['fps'])")
FRAME=$(python3 -c "print(int(float('$2')*$FPS))")
cd "$ROOT/templates/remotion"
npx remotion still src/index.ts Main "$OUT" --props="$VD/project/timeline.json" --public-dir="$VD/assets" --frame="$FRAME" --gl=angle --log=error
echo "$OUT"
