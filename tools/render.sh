#!/bin/bash
# Render a video with the shared Remotion engine.  tools/render.sh <video_dir>
# Uses <video_dir>/project/timeline.json as props and <video_dir>/assets as the public folder.
# Per-video scene components (<video_dir>/project/custom/*.tsx, written by the animator) are copied into the engine for this render.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; VD="$(cd "$1" && pwd)"
SRC="$ROOT/templates/remotion/src/custom"
find "$SRC" -mindepth 1 ! -name index.ts -delete
{ echo "// Generated by tools/render.sh from <video>/project/custom/*.tsx. Do not edit by hand."
  names=()
  for f in "$VD"/project/custom/*.tsx; do [ -f "$f" ] || continue; n="$(basename "$f" .tsx)"; cp "$f" "$SRC/$n.tsx"; names+=("$n"); echo "import $n from \"./$n\";"; done
  echo "export const custom: Record<string, React.FC<any>> = { $(IFS=,; echo "${names[*]}" | sed 's/,/, /g') };"; } > "$SRC/index.ts"
cd "$ROOT/templates/remotion"
npx remotion render src/index.ts Main "$VD/final.mp4" --props="$VD/project/timeline.json" --public-dir="$VD/assets" \
  --codec=h264 --crf=18 --concurrency=4 --gl=angle --log=error
echo "$VD/final.mp4"
